// Generate a rule from e18e's `native` manifest.
//
// e18e curates "this package has a native equivalent" and — usefully — already
// maps each one to a web-features id. What their tooling does not do is check it
// against *your* browserslist, which is the one thing this tool is for. So the
// data comes from them and the judgement stays here.
//
//   node scripts/build-e18e-rule.mjs
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

const require = createRequire(import.meta.url)
const manifest = require('module-replacements/manifests/native.json')

// Hand-written rules win: they carry a specific verdict and, for polyfills, the
// codemod. Imported one by one rather than through rules/index.js, which pulls in
// the file this script is writing.
const handWritten = await Promise.all([
  import('../dist/rules/floating-ui.js'),
  import('../dist/rules/polyfills.js'),
  import('../dist/rules/absorbed.js'),
  import('../dist/rules/enter-exit.js'),
  import('../dist/rules/dialog.js'),
  import('../dist/rules/scroll-animations.js'),
])
const claimed = new Set(handWritten.flatMap((mod) => mod.default.packages))

const entries = []
const skipped = []
const deferred = []

for (const [pkg, mapping] of Object.entries(manifest.mappings)) {
  if (mapping.type !== 'module') continue

  if (claimed.has(pkg)) {
    deferred.push(pkg)
    continue
  }

  const replacement = manifest.replacements[mapping.replacements?.[0]]
  if (!replacement?.webFeatureId) {
    skipped.push(pkg)
    continue
  }

  const { featureId, compatKey } = replacement.webFeatureId
  // A compat key is narrower than a whole feature, so prefer it when both exist.
  const requirement = compatKey ? `bcd:${compatKey}` : `feature:${featureId}`

  const docs = replacement.url?.type === 'mdn'
    ? `https://developer.mozilla.org/docs/${replacement.url.id}`
    : 'https://e18e.dev/guide/replacements.html'

  entries.push({ pkg, requirement, to: replacement.id, docs })
}

entries.sort((a, b) => a.pkg.localeCompare(b.pkg))

const table = entries
  .map((e) => `  ${JSON.stringify(e.pkg)}: { requirement: ${JSON.stringify(e.requirement)}, to: ${JSON.stringify(e.to)}, docs: ${JSON.stringify(e.docs)} },`)
  .join('\n')

const file = `// Generated by \`npm run build:e18e\` — do not edit.
//
// Source: e18e's module-replacements \`native\` manifest (MIT), which curates
// packages with a native equivalent and maps each to a web-features id.
// https://github.com/es-tooling/module-replacements
//
// What this rule adds on top: the same list, judged against your browserslist.

import type { Requirement, Rule } from '../types.js'

interface NativeReplacement {
  requirement: Requirement
  to: string
  docs: string
}

const NATIVE: Record<string, NativeReplacement> = {
${table}
}

const rule: Rule = {
  id: 'e18e-native',
  title: 'Packages with a native equivalent (e18e)',
  packages: Object.keys(NATIVE),
  requirementsFor: (pkg) => {
    const entry = NATIVE[pkg]
    return entry ? [entry.requirement] : []
  },
  replacementFor: (pkg) => NATIVE[pkg]?.to ?? 'a native API',
  docsFor: (pkg) => NATIVE[pkg]?.docs,
  docs: 'https://e18e.dev/guide/replacements.html',

  inspect({ pkg }) {
    return {
      verdict: 'check',
      note: \`\${NATIVE[pkg]?.to ?? 'A native API'} covers this. Call sites need rewriting.\`,
    }
  },
}

export default rule
`

writeFileSync(new URL('../src/rules/e18e-native.generated.ts', import.meta.url), file)
console.log(
  `build-e18e: ${entries.length} packages` +
    ` (${skipped.length} skipped — no web-features mapping,` +
    ` ${deferred.length} already covered by a hand-written rule: ${deferred.join(', ')})`,
)
